"""Write core/hooks.json and docs/HOOKS.md from the sources (the hook surface).

  python core/tools/hooks_table.py          rewrite both files
  python core/tools/hooks_table.py --check  fail if either is out of date

Read from the code, so the table cannot drift:
  * shared hooks: the Hook enum (core/runtime/hod_hooks.h) and its addresses
    and names (core/runtime/hod_hub.cpp);
  * every HOD_HOOK / HOD_SHAPE_OBSERVER registration in core/ and mods/;
  * every REX_EXTERN(sub_XXXXXXXX) override a section defines itself;
  * the same-shard call rewrites (core/cmake/hodmods.cmake).
"""
import json
import re
import sys
from pathlib import Path

import hodpaths

REPO = hodpaths.REPO
SECTION_OF = {  # source folder -> repo section
    "core/runtime": "core", "mods/shield-rod/src": "shield-rod", "mods/familiars/src": "familiars",
    "mods/glyphs/src": "glyphs", "mods/nathan/src": "nathan", "mods/catacombs/src": "catacombs",
}
MOD_ID = {"kCore": "core", "kShieldRod": "shield-rod", "kFamiliars": "familiars", "kRefectio": "refectio",
          "kArmaCustos": "arma-custos", "kNathan": "nathan", "kCatacombs": "catacombs"}


def sources():
    for folder, section in SECTION_OF.items():
        for p in sorted((REPO / folder).glob("*.cpp")):
            yield section, p


def build():
    header = (REPO / "core/runtime/hod_hooks.h").read_text(encoding="utf-8")
    enum = re.search(r"enum class Hook : uint8_t \{(.*?)kCount", header, re.S).group(1)
    hooks = re.findall(r"^\s*(k\w+),\s*//\s*([0-9A-F]{8})\s+(.*)$", enum, re.M)
    hub = (REPO / "core/runtime/hod_hub.cpp").read_text(encoding="utf-8")
    names = re.findall(r'\{0x([0-9A-F]{8}), "([^"]+)"\}', hub)
    assert [h[1] for h in hooks] == [a for a, _ in names], "hook enum and hub table disagree"
    table = {h[0]: {"address": h[1], "name": n, "role": h[2].strip(), "chain": [], "observers": []}
             for h, (_, n) in zip(hooks, names)}
    overrides = []
    for section, p in sources():
        text = p.read_text(encoding="utf-8")
        rel = p.relative_to(REPO).as_posix()
        for m in re.finditer(r"HOD_HOOK\((k\w+),\s*(k\w+),\s*(-?\d+),\s*(\w+)\)", text):
            hook, mod, order, fn = m.groups()
            table[hook]["chain"].append({"feature": MOD_ID[mod], "order": int(order), "handler": fn, "file": rel})
        for m in re.finditer(r"HOD_SHAPE_OBSERVER\((k\w+),\s*(-?\d+),\s*(\w+)\)", text):
            mod, order, fn = m.groups()
            table["kShapeRegister"]["observers"].append({"feature": MOD_ID[mod], "order": int(order), "handler": fn, "file": rel})
        for m in re.finditer(r"REX_EXTERN\(sub_([0-9A-F]{8})\)\s*\{(?=(.{0,160}))", text, re.S):
            address, body = m.groups()
            gated = re.search(r"HOD_PASS_IF_OFF\((k\w+)", body)
            owner = "hub" if rel == "core/runtime/hod_overrides.cpp" else section
            overrides.append({"address": address, "owner": owner, "file": rel,
                              "switch": MOD_ID[gated.group(1)] if gated else None})
    for h in table.values():
        h["chain"].sort(key=lambda e: e["order"])
        h["observers"].sort(key=lambda e: e["order"])
    cmake = (REPO / "core/cmake/hodmods.cmake").read_text(encoding="utf-8")
    block = re.search(r"set\(_hodmods_rewrites(.*?)\)", cmake, re.S).group(1)
    rewrites = {shard: fns.split(",") for shard, fns in re.findall(r'"(\d+):([^"]+)"', block)}
    return {
        "about": "Generated by core/tools/hooks_table.py from the sources; do not edit.",
        "dispatch": "A shared hook runs its chain lowest order first (outermost); each handler calls next() where the rest, "
                    "ending in the game's own function, should run. Handlers of a switched-off feature are skipped.",
        "shared_hooks": [dict(id=k, **v) for k, v in table.items()],
        "overrides": sorted(overrides, key=lambda o: (o["owner"], o["address"])),
        "shard_rewrites": rewrites,
    }


def markdown(data):
    out = ["# Hook surface", "",
           "Generated by `core/tools/hooks_table.py` from the sources (do not edit by hand). "
           "Machine-readable copy: [`core/hooks.json`](../core/hooks.json).", "",
           "## Shared hooks (one definition, in the hub)", "",
           "Each chain runs top to bottom (lowest order first). A handler calls `next()` before, after or "
           "around its own work, or not at all to consume the call; the game's function runs at the end. "
           "A handler that works *after* `next()` therefore does its work later than the handlers below it.", ""]
    for h in data["shared_hooks"]:
        out += [f"### `{h['address']}` {h['name']}", "", h["role"], ""]
        if h["chain"]:
            out += ["| Order | Feature | Handler | File |", "| --- | --- | --- | --- |"]
            out += [f"| {e['order']} | {e['feature']} | `{e['handler']}` | `{e['file']}` |" for e in h["chain"]]
        else:
            out += ["No handlers: only the hub's own behaviour (see `core/runtime/hod_overrides.cpp`)."]
        if h["observers"]:
            out += ["", "Shape observers, called under the collision lock after the game's registration:", "",
                    "| Order | Feature | Observer | File |", "| --- | --- | --- | --- |"]
            out += [f"| {e['order']} | {e['feature']} | `{e['handler']}` | `{e['file']}` |" for e in h["observers"]]
        out.append("")
    out += ["## Overrides", "",
            "Every guest function the exe or a module defines. `hub` rows are the shared hooks above plus the "
            "collision lock (`823C5098`) and the collision crash guard (`823C4EC8`). A section's own override "
            "passes straight to the game while its switch is off; module overrides (Nathan's `836Dxxxx`, the "
            "Catacombs modules) run only when their DLC package is installed.", "",
            "| Address | Owner | Switch | File |", "| --- | --- | --- | --- |"]
    out += [f"| `{o['address']}` | {o['owner']} | {o['switch'] or '-'} | `{o['file']}` |" for o in data["overrides"]]
    out += ["", "## Same-shard call rewrites", "",
            "The code generator emits direct calls inside a shard, and LLVM may fold them to the local body, "
            "bypassing an override. `core/cmake/hodmods.cmake` rewrites these call sites to the guest dispatch "
            "table at configure time. A runtime loader that installs overrides by replacing dispatch-table "
            "entries needs the same rewrites.", "",
            "| Shard (`generated/default/harmonyrecomp_recomp.N.cpp`) | Functions |", "| --- | --- |"]
    out += [f"| {s} | " + ", ".join(f"`{f}`" for f in fns) + " |" for s, fns in data["shard_rewrites"].items()]
    return "\n".join(out) + "\n"


def main():
    data = build()
    targets = {REPO / "core/hooks.json": json.dumps(data, indent=1) + "\n", REPO / "docs/HOOKS.md": markdown(data)}
    if "--check" in sys.argv:
        stale = [p for p, text in targets.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print("out of date:", p.relative_to(REPO))
        return 1 if stale else 0
    for p, text in targets.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print("wrote", p.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
